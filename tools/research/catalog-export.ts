/**
 * Read-only catalog export for the development research engine.
 * Bundled and run by scripts/export-catalog.mjs; it never writes app data.
 * Output must be deterministic: no timestamps, stable ordering.
 */
import { RECIPES } from "../../src/data/recipes";
import { approvedIngredientInput, recipeReviewCoverage } from "../../src/data/usdaApprovals";

export interface CatalogProvenance {
  sourceCommit: string;
  dirtyTree: boolean;
}

export function buildCatalog(provenance: CatalogProvenance) {
  const recipes = RECIPES.map((r) => {
    const lines = r.structuredIngredients.map((line, index) => {
      const input = approvedIngredientInput(line, r.id);
      return {
        index,
        raw: r.ingredients[index] ?? null,
        structured: line,
        approvedMapping: input
          ? { fdcId: input.fdcId, grams: input.grams, portionId: input.portionId }
          : null,
      };
    });
    const coverage = recipeReviewCoverage(r);
    const estimate = r.nutritionEstimate ?? null;
    return {
      id: r.id,
      name: r.name,
      servings: r.servings,
      lines,
      approvedCount: coverage.approved.length,
      totalCount: r.structuredIngredients.length,
      unapproved: coverage.unreviewed,
      estimate: estimate
        ? {
            published: true,
            status: estimate.status,
            // The Rainbow Fruit Skewers pilot maps its fruit through its own
            // approved inputs, not through approvedIngredientInput.
            inputs: estimate.ingredients.map((i) => ({
              name: i.name, fdcId: i.fdcId, grams: i.grams, portionId: i.portionId,
            })),
          }
        : { published: false },
    };
  });
  const catalog = { kind: "moodmeal-catalog-export", ...provenance, recipeCount: recipes.length, recipes };
  const coverage = {
    kind: "moodmeal-coverage-report",
    ...provenance,
    recipeCount: recipes.length,
    publishedEstimates: recipes.filter((r) => r.estimate.published).map((r) => r.id),
    recipes: recipes
      .map((r) => ({
        id: r.id,
        name: r.name,
        approved: r.approvedCount,
        total: r.totalCount,
        published: r.estimate.published,
        unapproved: r.unapproved,
      }))
      .sort((a, b) => a.unapproved.length - b.unapproved.length || a.id.localeCompare(b.id)),
  };
  const md = [
    "# Recipe USDA coverage",
    "",
    `Source commit ${provenance.sourceCommit}${provenance.dirtyTree ? " (working tree has uncommitted changes)" : ""}.`,
    "Generated by `npm run export:catalog`. Approved counts use exact recipe-scoped approvals only; the Rainbow Fruit Skewers pilot maps its fruit through its own estimate inputs.",
    "",
    `Published estimates: ${coverage.publishedEstimates.length} of ${recipes.length}.`,
    "",
    "| Recipe | Approved | Published | Unapproved ingredients |",
    "| --- | --- | --- | --- |",
    ...coverage.recipes.map(
      (r) => `| ${r.name} | ${r.approved}/${r.total} | ${r.published ? "yes" : "no"} | ${r.unapproved.join("; ") || "none"} |`,
    ),
    "",
  ].join("\n");
  return { catalog, coverage, md };
}
