// Regenerates src/data/mealTagReviews.ts from the batch 5 meal tag rule (src/lib/mealTagRule.ts).
// Run: node tools/research/generate-meal-tag-reviews.mjs
// Owner decision 2026-11-04 (docs/research/STAGE-D-BATCH-5.md): withdraw only tags shown to fall
// below the rule; record every other tag's status. Review the diff before committing.
import { build } from "esbuild";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { createRequire } from "node:module";
import { root } from "../../scripts/esbuild.config.mjs";

const dir = fs.mkdtempSync(path.join(os.tmpdir(), "moodmeal-meal-tags-"));
try {
  const entry = path.join(dir, "entry.ts");
  fs.writeFileSync(entry, `
    import { RECIPES } from ${JSON.stringify(path.join(root, "src/data/recipes").split(path.sep).join("/"))};
    import { checkMealTags } from ${JSON.stringify(path.join(root, "src/lib/mealTagRule").split(path.sep).join("/"))};
    export const checks = RECIPES.flatMap(checkMealTags);
  `);
  await build({
    entryPoints: [entry], absWorkingDir: root, bundle: true, platform: "node", format: "cjs",
    outfile: path.join(dir, "entry.cjs"), logLevel: "error",
    loader: { ".png": "file", ".jpg": "file", ".jpeg": "file", ".svg": "file", ".gif": "file", ".webp": "file" },
  });
  const { checks } = createRequire(import.meta.url)(path.join(dir, "entry.cjs"));
  const reviews = checks.map((c) => ({ ...c, decision: c.status === "below" ? "needs-review" : "published" }));
  const ts = `import type { MealTagCheck } from "../lib/mealTagRule";

/**
 * Meal nutrient tags checked against the stage D batch 5 rule (owner decisions 2026-11-04).
 * Generated by tools/research/generate-meal-tag-reviews.mjs; do not edit by hand.
 * "needs-review" tags (shown to fall below) are withheld from meals; "not-shown" tags stay
 * visible with ingredient-level wording until their ingredients have approved gram weights.
 */
export interface MealTagReview extends MealTagCheck {
  decision: "published" | "needs-review";
}
export const MEAL_TAG_REVIEW_DATE = "2026-11-04";
export const MEAL_TAG_REVIEWS: MealTagReview[] = ${JSON.stringify(reviews, null, 2)};
`;
  fs.writeFileSync(path.join(root, "src/data/mealTagReviews.ts"), ts);
  const count = (s) => reviews.filter((r) => r.status === s).length;
  console.log(`${reviews.length} meal tags: ${count("meets")} meet, ${count("below")} below, ${count("not-shown")} not shown`);
} finally {
  fs.rmSync(dir, { recursive: true, force: true });
}
